from nltk.translate.bleu_score import sentence_bleu, SmoothingFunction



def compute_bleu(candidates, reference, n_gram=4, smoothing=True):
    """
    Compute BLEU scores for multiple generated sentences compared to a single reference sentence.

    Args:
        generated_sentences (list of str): Sentences to evaluate.
        reference_sentence (str): The single reference sentence.
        n_gram (int): Maximum n-gram size (default BLEU-4).
        smoothing (bool): Whether to apply smoothing to avoid zero scores.

    Returns:
        list of float: BLEU scores for each generated sentence.
        float: Average BLEU score across all inputs.
    """
    ref_tokens = reference.split()
    weight = tuple([1.0 / n_gram] * n_gram) # Equal weights for n-grams e.g., (0.25, 0.25, 0.25, 0.25) for BLEU-4
    smoothie = SmoothingFunction().method4 if smoothing else None

    bleu_scores = []
    for gen in candidates:
        gen_tokens = gen.split()
        score = sentence_bleu([ref_tokens], gen_tokens, weights=weight, smoothing_function=smoothie)
        bleu_scores.append(score)

    average_score = sum(bleu_scores) / len(bleu_scores) if bleu_scores else 0.0
    return bleu_scores, average_score



    
def compute_proficiency_matching_score(generated_content: str, student_levels: dict) -> dict[str, int]:
    """
    Computes a matching score (0 or 1) for each arithmetic aspect (Addition, Subtraction, etc.)
    by comparing the presence of symbols (+, -, *, /) in generated content against the student's
    proficiency levels (Strong, Normal, Weak).

    Args:
        generated_content: Text generated by the model (may contain arithmetic symbols).
        student_levels: Dictionary mapping aspects to proficiency levels.
            Format: {"Addition": "Strong", "Subtraction": "Weak", ...}
        aspect_symbols: Optional custom mapping of aspects to symbols.
            Default: {"Addition": "+", "Subtraction": "-", ...}

    Returns:
        Dictionary with scores (1 = match, 0 = mismatch) for each aspect.
        Example: {"Addition": 1, "Subtraction": 0, ...}
    """


    # Symbols to aspects mapping
    aspect_symbols = {
        "Addition": "+",
        "Subtraction": "-",
        "Multiplication": "*",
        "Division": "/"
    }

    # Initialize scores
    scores = {aspect: 0 for aspect in aspect_symbols.keys()}
    
    for aspect, symbol in aspect_symbols.items():
        symbol_in_content = symbol in generated_content
        student_level = student_levels.get(aspect, "Strong")  # Default to 'Strong'
            
        # Logic: Symbol should ONLY appear if level is Weak/Normal
        if student_level in ["Weak", "Normal"]:
            scores[aspect] = 1 if symbol_in_content else 0
        else:  # Strong level: Symbol should NOT appear
            scores[aspect] = 0 if symbol_in_content else 1


    return scores